-- ====================================================
-- Migration PostgreSQL compatível com enums Java
-- ====================================================

-- 1️⃣ Drop tables existentes
DROP TABLE IF EXISTS usuario_setor_tab CASCADE;
DROP TABLE IF EXISTS usuario_funcao_tab CASCADE;
DROP TABLE IF EXISTS usuario_endereco_tab CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS pessoa CASCADE;
DROP TABLE IF EXISTS setor CASCADE;
DROP TABLE IF EXISTS funcao CASCADE;
DROP TABLE IF EXISTS endereco CASCADE;

-- 2️⃣ Criar tipos ENUM para PostgreSQL
CREATE TYPE funcao_enum AS ENUM ('GERENTE', 'OPERADOR', 'AUXILIAR');

CREATE TYPE setor_enum AS ENUM (
    'MANUTENCAO', 'PENDENTES', 'SEM_PLACA', 'REPARO_SIMPLES',
    'DANOS_GRAVES', 'PRONTAS_PARA_ALUGAR', 'MOTOR_DEFEITUOSO', 'AGENDADAS_PARA_MANUTENCAO'
);

-- 3️⃣ Criar tabelas principais
CREATE TABLE funcao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome funcao_enum NOT NULL
);

CREATE TABLE endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cep VARCHAR(20),
    logradouro VARCHAR(255),
    complemento VARCHAR(255),
    unidade VARCHAR(50),
    bairro VARCHAR(100),
    localidade VARCHAR(100),
    uf VARCHAR(5),
    estado VARCHAR(100),
    regiao VARCHAR(50)
);

CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome setor_enum NOT NULL,
    descricao VARCHAR(255)
);

CREATE TABLE pessoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    cpf VARCHAR(255),
    data_nascimento DATE,
    email VARCHAR(255)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    senha VARCHAR(255)
);

-- 4️⃣ Tabelas de relacionamento
CREATE TABLE usuario_funcao_tab (
    id_usuario BIGINT NOT NULL,
    id_funcao BIGINT NOT NULL,
    PRIMARY KEY (id_funcao, id_usuario)
);

CREATE TABLE usuario_setor_tab (
    id_usuario BIGINT NOT NULL,
    id_setor BIGINT NOT NULL,
    PRIMARY KEY (id_setor, id_usuario)
);

CREATE TABLE usuario_endereco_tab (
    id_usuario BIGINT NOT NULL,
    id_endereco BIGINT NOT NULL,
    PRIMARY KEY (id_usuario, id_endereco)
);
